-- ================= EXPORT_EVENTS 25M =================
CREATE OR REPLACE TABLE EXPORT_EVENTS AS
SELECT SEQ8()::NUMBER AS export_id,
       DATEADD('minute', -UNIFORM(0,86400,RANDOM()), CURRENT_TIMESTAMP()) AS export_ts,
       'usr_'||LPAD(UNIFORM(1,300,RANDOM()),3,'0') AS user_name,
       UNIFORM(50000,5000000,RANDOM())::NUMBER AS bytes_out
FROM TABLE(GENERATOR(ROWCOUNT=>25000000));

