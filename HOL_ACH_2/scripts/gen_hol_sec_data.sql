-- ================= CUSTOMERS 5M =================
CREATE OR REPLACE TABLE CUSTOMERS AS
SELECT SEQ8()::NUMBER AS customer_id,
       'Cliente '||SEQ8() AS full_name,
       'user'||SEQ8()||'@correo.com' AS email,
       LPAD(UNIFORM(1000000000,9999999999,RANDOM()),10,'0') AS national_id,
       '****-****-****-'||LPAD(UNIFORM(0,9999,RANDOM()),4,'0') AS card_last4,
       ARRAY_CONSTRUCT('Bogota','Medellin','Cali','Barranquilla')[UNIFORM(0,3,RANDOM())]::STRING AS branch_city
FROM TABLE(GENERATOR(ROWCOUNT=>5000000));

-- ================= UNLOAD a S3 =================
COPY INTO @stg_hol/auth_logins/data_ FROM AUTH_LOGINS
  FILE_FORMAT=(TYPE=CSV FIELD_DELIMITER=';' COMPRESSION=GZIP) HEADER=TRUE MAX_FILE_SIZE=100000000 OVERWRITE=TRUE;
COPY INTO @stg_hol/export_events/data_ FROM EXPORT_EVENTS
  FILE_FORMAT=(TYPE=CSV FIELD_DELIMITER=';' COMPRESSION=GZIP) HEADER=TRUE MAX_FILE_SIZE=50000000 OVERWRITE=TRUE;
COPY INTO @stg_hol/customers/data_ FROM CUSTOMERS
  FILE_FORMAT=(TYPE=CSV FIELD_DELIMITER=';' COMPRESSION=GZIP) HEADER=TRUE MAX_FILE_SIZE=100000000 OVERWRITE=TRUE;

SELECT 'AUTH_LOGINS' AS tabla, COUNT(*) AS filas FROM AUTH_LOGINS
UNION ALL SELECT 'EXPORT_EVENTS', COUNT(*) FROM EXPORT_EVENTS
UNION ALL SELECT 'CUSTOMERS', COUNT(*) FROM CUSTOMERS;
