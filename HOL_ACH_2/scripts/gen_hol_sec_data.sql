-- ================= AUTH_LOGINS 20M (pais fijo por usuario) =================
CREATE OR REPLACE TABLE AUTH_LOGINS AS
WITH base AS (
  SELECT SEQ8() AS event_id,
         UNIFORM(1,300,RANDOM()) AS uidx,
         DATEADD('minute', -UNIFORM(0, 86400, RANDOM()), CURRENT_TIMESTAMP()) AS event_ts,
         IFF(UNIFORM(1,100,RANDOM())<=12,'FAIL','SUCCESS') AS status,
         UNIFORM(1,255,RANDOM()) AS o1, UNIFORM(1,255,RANDOM()) AS o2,
         UNIFORM(1,255,RANDOM()) AS o3, UNIFORM(1,255,RANDOM()) AS o4
  FROM TABLE(GENERATOR(ROWCOUNT=>20000000))
)
SELECT event_id::NUMBER AS event_id,
       event_ts,
       'usr_'||LPAD(uidx,3,'0') AS user_name,
       ARRAY_CONSTRUCT('Bogota','Medellin','Lima','Madrid','Miami','Frankfurt','Singapore')[MOD(uidx,7)]::STRING AS city,
       ARRAY_CONSTRUCT('CO','CO','PE','ES','US','DE','SG')[MOD(uidx,7)]::STRING AS country,
       o1||'.'||o2||'.'||o3||'.'||o4 AS client_ip,
       status
FROM base;

